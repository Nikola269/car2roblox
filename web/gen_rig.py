"""Writes web/src/45_rig_lua.js from the Lua templates in car2roblox/rigscript.py (single source of truth)."""
import json, sys
from pathlib import Path
root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root))
from car2roblox import rigscript, __version__
out = ("// generated by web/gen_rig.py from car2roblox/rigscript.py - do not edit\n"
       f"const RIG_DRIVER = {json.dumps(rigscript._DRIVER)};\n"
       f"const RIG_TEMPLATE = {json.dumps(rigscript._TEMPLATE)};\n"
       f"const APP_VERSION = {json.dumps(__version__)};\n")
(root / "web" / "src" / "45_rig_lua.js").write_text(out)
print("wrote", len(out), "bytes")
