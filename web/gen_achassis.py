"""Writes web/src/47_achassis_data.js from the vendored A-Chassis scripts in
car2roblox/achassis.py / car2roblox/vendor/achassis/ (single source of truth)."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root))
from car2roblox import achassis  # noqa: E402

sources = {
    "initialize": achassis.vendor_source("Initialize.luau"),
    "readme": achassis.vendor_source("README.luau"),
    "units": achassis.vendor_source("Units.luau"),
    "drive": achassis.vendor_source("Drive.luau"),
}
tune_stock = achassis.vendor_source("A-Chassis Tune.luau")

out = (
    "// generated by web/gen_achassis.py from car2roblox/vendor/achassis/ - do not edit\n"
    f"const ACHASSIS_SOURCES = {json.dumps(sources)};\n"
    f"const ACHASSIS_TUNE_STOCK = {json.dumps(tune_stock)};\n"
    f"const ACHASSIS_VALUES_SPEC = {json.dumps([list(t) for t in achassis.VALUES_SPEC])};\n"
)
(root / "web" / "src" / "47_achassis_data.js").write_text(out)
print("wrote", len(out), "bytes")
